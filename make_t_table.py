#!/usr/bin/env python3
"""Generate the t table for Chapter 10 and splice it into 10_t_chi_f.md.

The table is COMPUTED, never typed. Its columns are the five upper-tail areas
the course's own table carries -- 0.10, 0.05, 0.025, 0.01, 0.005 -- so that a
student reading the book and a student holding the Checkpoint table are looking
at the same five numbers in the same order.

Every value the surrounding prose quotes is asserted here as well, against the
figures already in circulation elsewhere in the course:

    nu = 10, 0.025   2.2281    quoted in this chapter's convergence table
    nu = 24, 0.025   2.0639    the invoice question, Lecture 9 and Lab 8
    nu = 35, 0.025   2.0301    the commute interval, Lecture 8 and Lab 8
    nu = inf, 0.025  1.9600    the normal, which is the bottom row

Usage:  python3 book/make_t_table.py
"""

import os
import re

from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
CHAPTER = os.path.join(HERE, "10_t_chi_f.md")

OPEN = "<!-- t-table: generated by make_t_table.py -->"
CLOSE = "<!-- end t-table -->"

#  The five upper-tail areas, in the order the handed-out table prints them.
#  The labels are spelled out rather than formatted, so the heading reads 0.10
#  and not 0.1 -- it must match the table the students hold on the day.
AREAS = [0.10, 0.05, 0.025, 0.01, 0.005]
LABELS = ["0.10", "0.05", "0.025", "0.01", "0.005"]
assert [float(s) for s in LABELS] == AREAS, "a heading has drifted from its area"

#  Degrees of freedom. Every integer to 30, then the thinning the printed tables
#  use, then the normal.
DFS = list(range(1, 31)) + [35, 40, 50, 60, 80, 100, 120]


def crit(df, area):
    """The t that leaves `area` in the upper tail, at `df` degrees of freedom."""
    return float(stats.t.ppf(1 - area, df))


def table():
    rows = []
    for df in DFS:
        rows.append((str(df), [crit(df, a) for a in AREAS]))
    #  the infinity row IS the normal, which is the whole point of printing it
    rows.append(("$\\infty$", [float(stats.norm.ppf(1 - a)) for a in AREAS]))
    return rows


ROWS = table()

# ------------------------------------------------------------------ the checks

#  1. the values the course already quotes elsewhere, to four decimals
KNOWN = [(10, 0.025, 2.2281),      # this chapter's convergence table
         (24, 0.025, 2.0639),      # invoice question: Lecture 9, Lab 8, practice set
         (24, 0.05, 1.7109),       # bracketing example below
         (24, 0.01, 2.4922),       # bracketing example below
         (24, 0.005, 2.7969),      # bracketing example below
         (24, 0.10, 1.3178),       # bracketing example below
         (35, 0.025, 2.0301),      # commute interval: Lecture 8, Lab 8
         (4, 0.025, 2.7764),       # this chapter's convergence table
         (30, 0.025, 2.0423),      # this chapter's convergence table
         (100, 0.025, 1.9840)]     # this chapter's convergence table
for df, a, want in KNOWN:
    got = crit(df, a)
    assert abs(got - want) < 5e-5, \
        "t(%s, %s) is %.4f, but the course prints %.4f" % (df, a, got, want)

#  2. the bottom row really is the normal, to the four decimals we print
for a in AREAS:
    assert abs(float(stats.norm.ppf(1 - a)) - crit(100000, a)) < 5e-5

#  3. monotone both ways: a smaller tail area needs a bigger cutoff, and a
#     bigger df needs a smaller one. If either fails the table is scrambled.
for _, vals in ROWS:
    assert vals == sorted(vals), "a row is not increasing as the area shrinks"
for j in range(len(AREAS)):
    col = [vals[j] for _, vals in ROWS]
    assert col == sorted(col, reverse=True), "a column is not falling with df"

#  4. the two p-values the bracketing example quotes
P32 = float(2 * stats.t.sf(3.2, 24))
P22 = float(2 * stats.t.sf(2.2, 24))
assert abs(P32 - 0.003841) < 5e-6 and abs(P22 - 0.037677) < 5e-6
#  ...and that each really does fall inside the bracket the table gives
assert P32 < 2 * 0.005                      # beyond the last column
assert 2 * 0.01 < P22 < 2 * 0.025           # between the 0.01 and 0.025 columns

# ------------------------------------------------------------------- the table

head = "| $\\nu$ | " + " | ".join(f"**{s}**" for s in LABELS) + " |"
rule = "|---|" + "---|" * len(AREAS)
body = [f"| {name} | " + " | ".join(f"{v:.4f}" for v in vals) + " |"
        for name, vals in ROWS]

MD = "\n".join([OPEN, "", head, rule] + body + ["", CLOSE])

# ------------------------------------------------------------------- splice it

text = open(CHAPTER).read()

if OPEN in text:
    start = text.index(OPEN)
    end = text.index(CLOSE) + len(CLOSE)
    text = text[:start] + MD + text[end:]
else:
    raise SystemExit("  no sentinel in 10_t_chi_f.md -- add:\n  %s\n  %s"
                     % (OPEN, CLOSE))

open(CHAPTER, "w").write(text)

#  5. the prose around the table must actually quote the numbers it claims to,
#     the same check make_more_practice.py runs on the practice problems.
for want in ["1.3178", "1.7109", "2.0639", "2.4922", "2.7969",
             "0.0038", "0.0377"]:
    assert want in text, "the prose no longer quotes %s" % want

print(f"  t table: {len(ROWS)} rows x {len(AREAS)} columns, spliced into "
      f"10_t_chi_f.md")
print(f"  checks: {len(KNOWN)} known values, monotone rows and columns, "
      f"infinity row = normal")
print(f"  bracketing example verified: p(t=3.2, 24) = {P32:.6f}, "
      f"p(t=2.2, 24) = {P22:.6f}")
